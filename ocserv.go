// OpenConnect (Cisco AnyConnect compatible) via ocserv: authentication and accounting
// go to the panel's RADIUS server, so ocserv never runs a script. groupconfig=true makes
// ocserv apply the reply attributes, and stats-report-time drives interim accounting.

func ocPool(in *Inbound) netip.Prefix {
	def := fmt.Sprintf("10.%d.0.0/16", 140+in.ID%30)
	p, err := netip.ParsePrefix(strSetting(in.Settings, "pool", def))
	if err != nil {
		p = netip.MustParsePrefix(def)
	}
	return p.Masked()
}

func ocservConf(in *Inbound, dir, run, radConf string) string {
	s := in.Settings
	pool := ocPool(in)
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	w("# generated by vpn-lite")
	w(`auth = "radius[config=%s,groupconfig=true]"`, radConf)
	w(`acct = "radius[config=%s]"`, radConf)
	w("tcp-port = %d", in.Port)
	w("udp-port = %d", in.Port)
	if l := strings.TrimSpace(in.Listen); l != "" && l != "0.0.0.0" {
		w("listen-host = %s", l)
	}
	w("socket-file = %s/ocserv-%d.sock", run, in.ID)
	w("pid-file = %s/ocserv-%d.pid", run, in.ID)
	w("use-occtl = true")
	w("occtl-socket-file = %s/occtl-%d.sock", run, in.ID)
	w("server-cert = %s/server.crt", dir)
	w("server-key = %s/server.key", dir)
	w("isolate-workers = false")
	w("max-clients = 0")
	w("max-same-clients = 0") // the panel enforces the device cap
	// Behind a relay every customer arrives from the same source address: ocserv's default
	// "ban an address after a few failed logins" would lock every customer out at once.
	w("max-ban-score = 0")
	w("ban-reset-time = 60")
	w("keepalive = 10")
	w("dpd = 10")
	w("mobile-dpd = 20")
	w("switch-to-tcp-timeout = 25")
	w("try-mtu-discovery = false")
	w("mtu = %d", intSetting(s, "mtu", 1420))
	w("auth-timeout = 240")
	w("stats-report-time = 60")
	w("device = vc%d-", in.ID)
	w("predictable-ips = false")
	w("default-domain = vpn.local")
	w("ipv4-network = %s", pool.Addr())
	w("ipv4-netmask = %s", prefixMask(pool.Bits()))
	w("dns = %s", strSetting(s, "dns1", "8.8.8.8"))
	w("dns = %s", strSetting(s, "dns2", "8.8.4.4"))
	w("route = default")
	w("cisco-client-compat = true")
	w("dtls-legacy = true")
	w("tls-priorities = \"NORMAL:%%SERVER_PRECEDENCE:%%COMPAT:-VERS-SSL3.0:-ARCFOUR-128\"")
	w("log-level = 1")
	return b.String()
}

func (e *Engine) ocservDaemons(dir, run, secret string) map[string]*procDaemon {
	out := map[string]*procDaemon{}
	e.st.mu.RLock()
	var ins []*Inbound
	for _, in := range e.st.st.Inbounds {
		if in.Protocol == "openconnect" && in.Enable {
			c := *in
			ins = append(ins, &c)
		}
	}
	e.st.mu.RUnlock()
	bin, _ := exec.LookPath("ocserv")
	if bin == "" {
		if len(ins) > 0 {
			Events.Add("error", "openconnect", "", "ocserv is not installed")
		}
		return out
	}
	for _, in := range ins {
		cert, key := e.ocCertificate(in)
		if cert == "" || key == "" {
			Events.Add("error", "openconnect", "", "inbound %d: could not prepare a TLS certificate; not started", in.ID)
			continue
		}
		d := filepath.Join(dir, "oc", strconv.Itoa(in.ID))
		os.MkdirAll(d, 0o700)
		writeIfChanged(filepath.Join(d, "server.crt"), cert+"\n", 0o644)
		writeIfChanged(filepath.Join(d, "server.key"), key+"\n", 0o600)
		radConf, err := writeRadiusClient(filepath.Join(d, "radius"), secret, "vl-oc", true)
		if err != nil {
			continue
		}
		body := ocservConf(in, d, run, radConf)
		conf := filepath.Join(d, "ocserv.conf")
		writeIfChanged(conf, body, 0o600)
		out[fmt.Sprint(in.ID)] = &procDaemon{name: fmt.Sprintf("ocserv-%d", in.ID), bin: bin,
			args:    []string{"-c", conf},
			pidFile: filepath.Join(run, fmt.Sprintf("ocserv-%d.pid", in.ID)), match: "ocserv",
			hash: fingerprint(body, cert, key, secret, radDictionary)}
	}
	return out
}

// killOcserv disconnects exactly one session. occtl identifies sessions by an internal
// id, so the session is found by its tunnel address (every string field is compared,
// which keeps this independent of occtl's exact JSON key names between versions).
func killOcserv(run string, s *Session) {
	sock := filepath.Join(run, fmt.Sprintf("occtl-%d.sock", s.InboundID))
	if s.VIP == "" { // no tunnel address known: drop by user name
		exec.Command("occtl", "-s", sock, "disconnect", "user", s.Email).Run()
		return
	}
	out, err := exec.Command("occtl", "-s", sock, "-j", "show", "users").Output()
	if err != nil {
		return
	}
	var users []map[string]any
	if json.Unmarshal(out, &users) != nil {
		return
	}
	for _, u := range users {
		match := false
		for _, v := range u {
			if str, ok := v.(string); ok && str == s.VIP {
				match = true
			}
		}
		if !match {
			continue
		}
		id := fmt.Sprint(u["ID"])
		if f, ok := u["ID"].(float64); ok {
			id = strconv.Itoa(int(f))
		}
		exec.Command("occtl", "-s", sock, "disconnect", "id", id).Run()
		return
	}
}

// ocCertificate picks the TLS certificate for a Cisco/OpenConnect inbound:
//  1. a Let's Encrypt certificate for its connection domain, when one exists on this host
//     (get one from the menu: vl -> certificate for a domain);
//  2. a certificate pasted into the inbound's settings;
//  3. otherwise a self-signed one for the connection domain, created once and stored.
func (e *Engine) ocCertificate(in *Inbound) (cert, key string) {
	dom := strings.TrimSpace(strSetting(in.Settings, "connDomain", ""))
	if dom != "" && !strings.ContainsAny(dom, "/\\") {
		c, err1 := os.ReadFile("/etc/letsencrypt/live/" + dom + "/fullchain.pem")
		k, err2 := os.ReadFile("/etc/letsencrypt/live/" + dom + "/privkey.pem")
		if err1 == nil && err2 == nil {
			return strings.TrimSpace(string(c)), strings.TrimSpace(string(k))
		}
	}
	cert = strings.TrimSpace(strSetting(in.Settings, "certificate", strSetting(in.Settings, "serverCert", "")))
	key = strings.TrimSpace(strSetting(in.Settings, "key", strSetting(in.Settings, "serverKey", "")))
	if cert != "" && key != "" {
		return cert, key
	}
	host := dom
	if host == "" {
		host = strings.TrimSpace(in.Listen)
	}
	if host == "" || host == "0.0.0.0" {
		host = "vpn-lite"
	}
	c, k, err := selfSignedPEM(host)
	if err != nil {
		return "", ""
	}
	e.st.mu.Lock()
	if cur := e.st.st.Inbounds[in.ID]; cur != nil {
		if cur.Settings == nil {
			cur.Settings = map[string]any{}
		}
		cur.Settings["certificate"], cur.Settings["key"] = c, k
		e.st.touch()
	}
	e.st.mu.Unlock()
	Events.Add("info", "openconnect", "", "inbound %d: created a self-signed certificate for %s", in.ID, host)
	return c, k
}
