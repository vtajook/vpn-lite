// L2TP: one xl2tpd + pppd per inbound. pppd authenticates every login through its
// radius plugin against the panel's RADIUS server, which accepts PAP, CHAP and
// MS-CHAPv2. That matters: phones and Windows speak MS-CHAPv2, but modems and routers
// usually only do PAP or CHAP, so refusing the older methods locks the modems out.
//
// IPsec (for phones) is a separate layer: strongSwan answers IKEv1 PSK on UDP 500/4500
// and protects only UDP/1701 in transport mode. Plain L2TP on the same port keeps working
// without IPsec because the IPsec policy exists only for peers that negotiated an SA.

func l2tpPool(in *Inbound) netip.Prefix {
	def := fmt.Sprintf("10.%d.0.0/16", 120+in.ID%30)
	p, err := netip.ParsePrefix(strSetting(in.Settings, "pool", def))
	if err != nil {
		p = netip.MustParsePrefix(def)
	}
	return p.Masked()
}

func poolRange(p netip.Prefix) (first, last, gw string) {
	a := p.Addr().As4()
	n := uint32(a[0])<<24 | uint32(a[1])<<16 | uint32(a[2])<<8 | uint32(a[3])
	size := uint32(1) << (32 - p.Bits())
	ip := func(v uint32) string {
		return fmt.Sprintf("%d.%d.%d.%d", byte(v>>24), byte(v>>16), byte(v>>8), byte(v))
	}
	return ip(n + 2), ip(n + size - 2), ip(n + 1)
}

func pppOptions(in *Inbound, radConf string) string {
	s := in.Settings
	mtu := intSetting(s, "mtu", 1280)
	if mtu < 1000 || mtu > 1500 {
		mtu = 1280
	}
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	w("# generated by vpn-lite")
	w("name vl-l2tp")
	w("auth") // authentication is required; the method is whatever the peer offers
	w("refuse-eap")
	w("ipcp-accept-local")
	w("ipcp-accept-remote")
	w("noccp")
	w("noipv6")
	w("ms-dns %s", strSetting(s, "dns1", "8.8.8.8"))
	w("ms-dns %s", strSetting(s, "dns2", "8.8.4.4"))
	w("mtu %d", mtu)
	w("mru %d", mtu)
	w("nodefaultroute")
	w("lcp-echo-interval 20")
	w("lcp-echo-failure 3")
	w("connect-delay 5000")
	w("plugin radius.so")
	w("radius-config-file %s", radConf)
	return b.String()
}

func xl2tpdConf(in *Inbound, optFile, ctlFile string) string {
	first, last, gw := poolRange(l2tpPool(in))
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	w("[global]")
	w("port = %d", in.Port)
	if l := strings.TrimSpace(in.Listen); l != "" && l != "0.0.0.0" {
		w("listen-addr = %s", l)
	}
	w("")
	w("[lns default]")
	w("ip range = %s-%s", first, last)
	w("local ip = %s", gw)
	w("require authentication = yes")
	w("name = vl-l2tp")
	w("pppoptfile = %s", optFile)
	w("length bit = yes")
	return b.String()
}

func (e *Engine) l2tpDaemons(dir, run string, secret string) map[string]*procDaemon {
	out := map[string]*procDaemon{}
	e.st.mu.RLock()
	var ins []*Inbound
	for _, in := range e.st.st.Inbounds {
		if in.Protocol == "l2tp" && in.Enable {
			c := *in
			ins = append(ins, &c)
		}
	}
	e.st.mu.RUnlock()
	bin, _ := exec.LookPath("xl2tpd")
	if bin == "" {
		if len(ins) > 0 {
			Events.Add("error", "l2tp", "", "xl2tpd is not installed")
		}
		return out
	}
	for _, in := range ins {
		d := filepath.Join(dir, "l2tp", strconv.Itoa(in.ID))
		os.MkdirAll(d, 0o700)
		radConf, err := writeRadiusClient(filepath.Join(d, "radius"), secret, "vl-l2tp", false)
		if err != nil {
			continue
		}
		opt := filepath.Join(d, "options")
		conf := filepath.Join(d, "xl2tpd.conf")
		optBody := pppOptions(in, radConf)
		confBody := xl2tpdConf(in, opt, "")
		writeIfChanged(opt, optBody, 0o600)
		writeIfChanged(conf, confBody, 0o600)
		pid := filepath.Join(run, fmt.Sprintf("xl2tpd-%d.pid", in.ID))
		out[fmt.Sprint(in.ID)] = &procDaemon{adoptUnknown: true, name: fmt.Sprintf("xl2tpd-%d", in.ID), bin: bin,
			args:    []string{"-c", conf, "-p", pid, "-C", filepath.Join(run, fmt.Sprintf("l2tp-%d.control", in.ID))},
			pidFile: pid, match: "xl2tpd", hash: fingerprint(optBody, confBody, secret)}
	}
	return out
}

// killPPP ends one pppd session. The radius plugin reports the ppp unit as NAS-Port,
// and pppd keeps /var/run/ppp<unit>.pid for that link.
func killPPP(s *Session) {
	dev := s.Dev
	if dev == "" || !strings.HasPrefix(dev, "ppp") {
		return
	}
	b, err := os.ReadFile("/var/run/" + dev + ".pid")
	if err != nil {
		return
	}
	if p, _ := strconv.Atoi(strings.TrimSpace(string(b))); p > 1 {
		syscall.Kill(p, syscall.SIGHUP) // pppd treats SIGHUP as a clean link teardown
	}
}

// ---------------------------------------------------------------- IPsec (strongSwan, swanctl)

const swanFile = "/etc/swanctl/conf.d/vpn-lite.conf"

func swanctlConf(psk string) string {
	return fmt.Sprintf(`# generated by vpn-lite
connections {
  vl-l2tp {
    version = 1
    local_addrs = %%any
    remote_addrs = %%any
    proposals = aes256-sha1-modp2048,aes128-sha1-modp2048,aes256-sha256-modp2048,aes256-sha1-modp1024,aes128-sha1-modp1024,3des-sha1-modp1024
    fragmentation = yes
    dpd_delay = 30s
    unique = no
    encap = yes
    local { auth = psk }
    remote { auth = psk }
    children {
      l2tp {
        mode = transport
        local_ts = dynamic[udp/1701]
        remote_ts = dynamic[udp]
        esp_proposals = aes256-sha1,aes128-sha1,aes256-sha256,aes128-sha256,3des-sha1
        rekey_time = 1h
        dpd_action = clear
      }
    }
  }
}
secrets {
  ike-vl {
    secret = %q
  }
}
`, psk)
}

// reconcileIPsec renders the strongSwan config from the first l2tp inbound that has
// IPsec enabled on port 1701 (IKEv1 PSK cannot select a key by anything but our own
// address, so one PSK serves the host) and (re)loads it only when the text changed.
func (e *Engine) reconcileIPsec() {
	e.st.mu.RLock()
	psk := ""
	for _, in := range e.st.sortedInbounds() {
		if in.Protocol == "l2tp" && in.Enable && boolSetting(in.Settings, "ipsecEnable", true) && in.Port == 1701 {
			if p := strSetting(in.Settings, "ipsecPsk", ""); p != "" {
				psk = p
				break
			}
		}
	}
	e.st.mu.RUnlock()
	if psk == "" {
		if _, err := os.Stat(swanFile); err == nil {
			os.Remove(swanFile)
			exec.Command("swanctl", "--load-all").Run()
		}
		return
	}
	body := swanctlConf(psk)
	if old, err := os.ReadFile(swanFile); err == nil && string(old) == body {
		return
	}
	os.MkdirAll(filepath.Dir(swanFile), 0o755)
	if err := os.WriteFile(swanFile, []byte(body), 0o600); err != nil {
		Events.Add("error", "ipsec", "", "write %s: %v", swanFile, err)
		return
	}
	exec.Command("systemctl", "enable", "--now", "strongswan").Run()
	if out, err := exec.Command("swanctl", "--load-all").CombinedOutput(); err != nil {
		Events.Add("error", "ipsec", "", "swanctl --load-all: %v %s", err, strings.TrimSpace(string(out)))
		return
	}
	Events.Add("daemon", "ipsec", "", "swanctl config loaded")
}
