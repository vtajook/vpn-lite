package main

import (
	"fmt"
	"net"
	"net/http"
	"net/netip"
	"strings"
)

var defaultCiphers = []string{"AES-256-GCM", "AES-128-GCM", "CHACHA20-POLY1305", "AES-256-CBC", "AES-192-CBC", "AES-128-CBC", "BF-CBC", "DES-EDE3-CBC"}

func ciphersOf(m map[string]any) []string {
	var out []string
	if arr, ok := m["ciphers"].([]any); ok {
		for _, v := range arr {
			if s, ok := v.(string); ok && s != "" {
				out = append(out, s)
			}
		}
	}
	if len(out) == 0 {
		out = defaultCiphers
	}
	return out
}

func needsLegacy(c []string) bool {
	for _, x := range c {
		if x == "BF-CBC" || x == "DES-EDE3-CBC" {
			return true
		}
	}
	return false
}

func firstCBC(c []string) string {
	for _, x := range c {
		if strings.HasSuffix(x, "-CBC") {
			return x
		}
	}
	return ""
}

func boolSetting(m map[string]any, k string, def bool) bool {
	if v, ok := m[k].(bool); ok {
		return v
	}
	return def
}

func tcpPort(in *Inbound) int {
	if boolSetting(in.Settings, "separatePorts", false) {
		if p := intSetting(in.Settings, "tcpPort", 0); p > 0 {
			return p
		}
	}
	return in.Port
}

// ovpnPool: tunnel subnet of one transport. Defaults keep UDP and TCP, and different
// inbounds, apart; 10.100+ stays clear of the old panel's 10.2.x / 10.3.x.
func ovpnPool(in *Inbound, proto string) netip.Prefix {
	key, def := "pool", fmt.Sprintf("10.%d.0.0/16", 100+in.ID%50)
	if proto == "tcp" {
		key, def = "poolTcp", fmt.Sprintf("10.%d.0.0/16", 150+in.ID%50)
	}
	p, err := netip.ParsePrefix(strSetting(in.Settings, key, def))
	if err != nil {
		p = netip.MustParsePrefix(def)
	}
	return p.Masked()
}

func prefixMask(bits int) string {
	m := net.CIDRMask(bits, 32)
	return fmt.Sprintf("%d.%d.%d.%d", m[0], m[1], m[2], m[3])
}

// ovpnServerConfig renders the daemon config. Authentication is NOT done by hooks:
// the daemon only talks to the panel over its management socket (management-client-auth),
// so OpenVPN's single event loop never waits for an exec'd process.
func ovpnServerConfig(in *Inbound, proto, dir, runDir string) string {
	s := in.Settings
	port := in.Port
	pstr := "udp"
	if proto == "tcp" {
		port, pstr = tcpPort(in), "tcp-server"
	}
	pool := ovpnPool(in, proto)
	dns1 := strSetting(s, "dns1", "8.8.8.8")
	dns2 := strSetting(s, "dns2", "8.8.4.4")
	mtu := intSetting(s, "mtu", 1350)
	if mtu < 1200 || mtu > 1500 {
		mtu = 1350
	}
	ciphers := ciphersOf(s)
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	w("# generated by vpn-lite — do not edit")
	if listen := strings.TrimSpace(in.Listen); listen != "" && listen != "0.0.0.0" {
		w("local %s", listen)
	}
	w("port %d", port)
	w("proto %s", pstr)
	w("dev vl%d%s", in.ID, proto[:1])
	w("dev-type tun")
	w("topology subnet")
	w("server %s %s", pool.Addr(), prefixMask(pool.Bits()))
	// Several devices share one username; the panel (not OpenVPN) decides who is
	// allowed to stay, so OpenVPN must not drop the old same-CN session on its own.
	w("duplicate-cn")
	w("username-as-common-name")
	w("verify-client-cert none")
	w(`push "redirect-gateway def1 bypass-dhcp"`)
	w(`push "dhcp-option DNS %s"`, dns1)
	w(`push "dhcp-option DNS %s"`, dns2)
	w(`push "block-ipv6"`)
	w("tun-mtu %d", mtu)
	w("mssfix %d", mtu)
	w("ca %s/ca.crt", dir)
	w("cert %s/server.crt", dir)
	w("key %s/server.key", dir)
	if strings.TrimSpace(strSetting(s, "tlsCrypt", "")) != "" {
		w("tls-crypt %s/tc.key", dir)
	}
	w("dh none")
	if needsLegacy(ciphers) {
		w("providers legacy default")
	}
	w("data-ciphers %s", strings.Join(ciphers, ":"))
	if c := firstCBC(ciphers); c != "" {
		w("data-ciphers-fallback %s", c)
	}
	w("cipher %s", ciphers[0])
	w("auth SHA256")
	w("management %s/ovpn-%d-%s.sock unix", runDir, in.ID, proto)
	w("management-client-auth")
	w("keepalive 10 60")
	w("persist-key")
	w("persist-tun")
	if proto == "udp" {
		w("explicit-exit-notify 1")
		w("fast-io")
	}
	w("status-version 3")
	w("verb 3")
	return b.String()
}

func (a *API) ovpnFile(w http.ResponseWriter, r *http.Request) {
	proto := r.PathValue("proto")
	a.st.mu.RLock()
	in := a.st.st.Inbounds[pathID(r)]
	a.st.mu.RUnlock()
	if in == nil || in.Protocol != "openvpn" {
		fail(w, "Inbound not found")
		return
	}
	cfg, err := ovpnClientConfig(in, proto, r.Host)
	if err != nil {
		fail(w, err.Error())
		return
	}
	w.Header().Set("Content-Type", "application/x-openvpn-profile")
	w.Header().Set("Content-Disposition", fmt.Sprintf(`attachment; filename="%s-%s.ovpn"`, safeName(in.Remark, in.ID), proto))
	w.Write([]byte(cfg))
}

func safeName(remark string, id int) string {
	var b strings.Builder
	for _, c := range remark {
		if c < 128 && (c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '-' || c == '_') {
			b.WriteRune(c)
		}
	}
	if b.Len() == 0 {
		return fmt.Sprintf("openvpn-%d", id)
	}
	return b.String()
}

func ovpnClientConfig(in *Inbound, proto, reqHost string) (string, error) {
	s := in.Settings
	if proto != "udp" && proto != "tcp" {
		return "", fmt.Errorf("proto must be udp or tcp")
	}
	if proto == "udp" && !boolSetting(s, "udpEnable", true) {
		return "", fmt.Errorf("UDP transport is disabled for this inbound")
	}
	if proto == "tcp" && !boolSetting(s, "tcpEnable", true) {
		return "", fmt.Errorf("TCP transport is disabled for this inbound")
	}
	ca := strings.TrimSpace(strSetting(s, "caCert", ""))
	if ca == "" {
		return "", fmt.Errorf("no CA certificate: generate certificates for this inbound first")
	}
	port := in.Port
	if proto == "tcp" {
		port = tcpPort(in)
	}
	type remote struct {
		host string
		port int
	}
	var remotes []remote
	if arr, ok := s["externalProxy"].([]any); ok {
		for _, e := range arr {
			m, _ := e.(map[string]any)
			d := strings.TrimSpace(strSetting(m, "dest", ""))
			if d == "" {
				continue
			}
			p := intSetting(m, "port", 0)
			if p == 0 {
				p = port
			}
			remotes = append(remotes, remote{d, p})
		}
	}
	if len(remotes) == 0 {
		h := strings.TrimSpace(strSetting(s, "connDomain", ""))
		if h == "" {
			h = strings.TrimSpace(in.Listen)
		}
		if h == "" || h == "0.0.0.0" {
			h = reqHost
			if hh, _, err := net.SplitHostPort(h); err == nil {
				h = hh
			}
		}
		if h == "" {
			return "", fmt.Errorf("could not determine server address; set an external proxy destination")
		}
		remotes = append(remotes, remote{h, port})
	}
	ciphers := ciphersOf(s)
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	w("client")
	w("dev tun")
	w("proto %s", proto)
	for _, r := range remotes {
		w("remote %s %d", r.host, r.port)
	}
	w("resolv-retry infinite")
	w("nobind")
	w("persist-key")
	w("persist-tun")
	if proto == "udp" {
		w("explicit-exit-notify 3")
	}
	w("remote-cert-tls server")
	w("auth-user-pass")
	w("setenv CLIENT_CERT 0")
	if in.Remark != "" {
		w("setenv FRIENDLY_NAME %q", in.Remark)
	}
	joined := strings.Join(ciphers, ":")
	if needsLegacy(ciphers) {
		w("setenv opt providers legacy default")
	}
	if c := firstCBC(ciphers); c != "" {
		w("setenv opt data-ciphers %s", joined)
		w("cipher %s", c)
	} else {
		w("data-ciphers %s", joined)
		w("cipher %s", ciphers[0])
	}
	w("auth SHA256")
	w("tun-mtu %d", intSetting(s, "mtu", 1350))
	w("verb 3")
	w("<ca>\n%s\n</ca>", ca)
	if tc := strings.TrimSpace(strSetting(s, "tlsCrypt", "")); tc != "" {
		w("<tls-crypt>\n%s\n</tls-crypt>", tc)
	}
	return b.String(), nil
}
